/**
 * Returns translated title, description, and highlights for a product in any of the 10 languages
 */
export function getProductTranslation(
  product: Product,
  lang: PrimaryLanguageCode
): { title: string; description: string; highlights: string[] } {
  // 1. Check custom hardcoded 10-language dictionary first
  if (PRODUCT_TRANSLATIONS[product.id]?.[lang]) {
    const custom = PRODUCT_TRANSLATIONS[product.id][lang];
    return {
      title: custom.title,
      description: custom.description,
      highlights: custom.highlights || product.highlights
    };
  }

  // 2. Check product.translations[lang]
  const prodTranslation = product.translations?.[lang];
  if (prodTranslation && prodTranslation.title) {
    return {
      title: prodTranslation.title,
      description: prodTranslation.description || product.description,
      highlights: prodTranslation.highlights || product.highlights
    };
  }

  // 3. Fallback to English translation if available
  const enTranslation = product.translations?.en;
  if (enTranslation && enTranslation.title) {
    return {
      title: enTranslation.title,
      description: enTranslation.description || product.description,
      highlights: enTranslation.highlights || product.highlights
    };
  }

  // 4. Default to product original fields
  return {
    title: product.title,
    description: product.description,
    highlights: product.highlights || []
  };
}

/**
 * Returns translated artisan story and details
 */
export function getArtisanTranslation(
  artisan: Artisan,
  lang: PrimaryLanguageCode
): { name: string; story: string; craftTypeName: string; generation: string } {
  const story = artisan.storyTranslations?.[lang] || artisan.storyTranslations?.en || artisan.story;
  const name = lang === 'en' ? artisan.name : (artisan.nativeName || artisan.name);
  return {
    name,
    story,
    craftTypeName: artisan.craftTypeName,
    generation: artisan.generation
  };
}
